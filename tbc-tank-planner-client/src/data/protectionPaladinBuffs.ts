import type { BuffDefinition, BuffVariant, StatBlock } from "../types";

function stats(overrides: Partial<StatBlock> = {}): StatBlock {
  return {
    stamina: 0,
    strength: 0,
    agility: 0,
    intellect: 0,
    armor: 0,
    arcaneResistance: 0,
    fireResistance: 0,
    frostResistance: 0,
    natureResistance: 0,
    shadowResistance: 0,
    defenseRating: 0,
    dodgeRating: 0,
    parryRating: 0,
    blockRating: 0,
    blockValue: 0,
    resilienceRating: 0,
    hitRating: 0,
    spellHitRating: 0,
    expertiseRating: 0,
    attackPower: 0,
    spellPower: 0,
    mp5: 0,
    ...overrides,
  };
}

function standardAndImproved(
  standardStats: Partial<StatBlock>,
  improvedStats: Partial<StatBlock>,
  improvedLabel = "Improved"
): BuffVariant[] {
  return [
    {
      id: "standard",
      label: "Standard",
      stats: stats(standardStats),
      effectKeys: [],
      appliesTo: [],
    },
    {
      id: "improved",
      label: improvedLabel,
      stats: stats(improvedStats),
      effectKeys: [],
      appliesTo: [],
    },
  ];
}

